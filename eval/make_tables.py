def comparison_table():
    rows = []
    for design, name in DESIGNS.items():
        a = load(f"agreement_d{design}")
        if not a:
            continue
        d = a["docket"]
        models = next(iter(a["models"].values())) or {}
        where = f"{', '.join(a['slice'])}, {', '.join(str(n) for n in a['scriptsPerRun'])} scripts, run {', '.join(a['runIds'])}"
        rows.append(f"| {name}: signs without a teacher | {ci(a, 'exactWhenCommits')} | {ci(a, 'withinOneWhenCommits')} | {ci(a, 'commits')} | {where} |")
        rows.append(f"| {name}: teacher-free floor | {ci(a, 'floorExact')} | {ci(a, 'floorWithinOne')} | all | {where} |")
        rows.append(f"| {name}: reader A alone (`{models.get('a', '?')}`) | {ci(a, 'readerAExact')} | {ci(a, 'readerAWithinOne')} | all | {where} |")
        rows.append(f"| {name}: reader B alone (`{models.get('b', '?')}`) | {ci(a, 'readerBExact')} | {ci(a, 'readerBWithinOne')} | all | {where} |")
    single = load("single_reader_d2_b")
    if single and single["runs"]:
        r1 = single["runs"][0]
        w, o = r1["exact"], r1["withinOne"]
        rows.append(f"| Design 2, reader B + code key only (`{r1['model']}`; one reader, not the two-reader design) | {w['pct']}% ({w['k']}/{w['n']}; 95% CI {w['low']} to {w['high']}) | {o['pct']}% ({o['k']}/{o['n']}; 95% CI {o['low']} to {o['high']}) | all | {r1['slice']}, {r1['scripts']} scripts, run {r1['runId']} |")
    published = load("published_baselines")
    for r in (published or {}).get("task13Rows", [])[:2]:
        rows.append(f"| Published, not run by Docket: `{r['model']}` ({r['mode']}), the same task-13 scripts | {r['exactPct']}% ({r['exact']}/{r['scripts']}) | {r['withinOnePct']}% | all | CHECK-MAT repo, {r['scripts']} task-13 scripts |")
    for r in (published or {}).get("rows", [])[:1]:
        rows.append(f"| Published, not run by Docket: `{r['model']}` ({r['mode']}) | {r['exactPct']}% | {r['withinOnePct']}% | all | CHECK-MAT repo, {r['scripts']} scripts |")
    if not rows:
        return []
    return [
        "### Headline: design 1, design 2 and one reader alone, task 13",
        "",
        "Exact and within one point of the official grade, with counts and Wilson 95% intervals. The published rows are the CHECK-MAT author's own per-script results in the repo's `model_results` files: two on the same 21 task-13 scripts, and the best on all 122 scripts for scale. Those are other models, not run by Docket. Sources: `eval/results/agreement_d1.json`, `eval/results/agreement_d2.json`, `eval/results/published_baselines.json`.",
        "",
        "| Setup | Exact | Within one | Share of scripts | Slice and run |",
        "|---|---|---|---|---|",
        *rows,
    ]


TASK_NAMES = {"15": "task 15 (inequality)", "16": "task 16 (loan word problem)", "18": "task 18 (parameter)", "pooled": "tasks 15, 16 and 18 pooled"}


def keyed_table():
    keyed = load("single_reader_d2_b_keyed")
    if not keyed or not keyed["tasks"]:
        return []
    lines = [
        "### Design 2, reader B + code key, beyond task 13 (Amendment 7)",
        "",
        f"One reader (`{keyed['model']}`), not the two-reader design. Run {keyed['runId']} on `{keyed['slice']}`: {keyed['scriptsGraded']} of {keyed['scriptsInSlice']} scripts graded"
        + (f"; not run: {', '.join(keyed['notRun'])}" if keyed["notRun"] else "")
        + ". Published: the CHECK-MAT authors' per-script results (with_true_solution) of the model with the most exact on the same scripts, not run by Docket. Exact two-sided McNemar on discordant scripts. Source: `eval/results/single_reader_d2_b_keyed.json`.",
        "",
        "| Task | Exact | Within one | Above / below official | Best published on the same scripts | Only Docket right | Only published right | McNemar p |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for task in ("15", "16", "18", "pooled"):
        row = keyed["tasks"].get(task)
        if not row:
            continue
        w, o, best = row["exact"], row["withinOne"], row["bestPublishedOnSameScripts"]
        published = f"`{best['model']}` {best['publishedExact']}/{best['scripts']}" if best else "none on all the same scripts"
        lines.append(
            f"| {TASK_NAMES[task]} | {w['pct']}% ({w['k']}/{w['n']}; 95% CI {w['low']} to {w['high']}) | {o['pct']}% ({o['k']}/{o['n']}; 95% CI {o['low']} to {o['high']}) | {row['aboveOfficial']} / {row['belowOfficial']} | {published} | "
            + (f"{best['firstOnlyRight']} | {best['secondOnlyRight']} | {best['mcnemarExactP']} |" if best else "- | - | - |")
        )
    sp = keyed.get("spreadExactPct")
    counts = ", ".join(f"{c['runId']} {c['exact']}/{c['scripts']}" for c in keyed.get("spreadCounts", []))
    lines += ["", f"Run-to-run spread, exact, on `{keyed['spreadOn']}`: " + (f"mean {sp['mean']}%, min {sp['min']}, max {sp['max']}, over {len(sp['runs'])} run(s) ({counts})." if sp else "not measured.")]
    if keyed.get("dailyCap"):
        lines.append(f"The run stopped on the provider's daily cap: {keyed['dailyCap'][:300]}")
    return lines


def main():
    global RESULTS, PROOF
    parser = argparse.ArgumentParser()
    parser.add_argument("--results-dir", type=Path, default=RESULTS)
    parser.add_argument("--proof", type=Path, default=PROOF)
    args = parser.parse_args()
    RESULTS, PROOF = args.results_dir, args.proof
    blocks = []
    summary = comparison_table()
    if summary:
        blocks.append(summary)
    singles = single_reader_tables()
    if singles:
        blocks.append(singles)
    keyed = keyed_table()
    if keyed:
        blocks.append(keyed)
    for design, label in DESIGNS.items():
        agreement = load(f"agreement_d{design}")
        if not agreement:
            continue
        blocks.append(agreement_table(agreement, load("published_baselines"), f"{label}: agreement with the official grade", f"agreement_d{design}"))
        spread = load(f"agreement_spread_d{design}")
        if spread:
            blocks.append(agreement_table(spread, None, f"{label}: run-to-run spread", f"agreement_spread_d{design}"))
        pt = paired_table(agreement, label, f"agreement_d{design}")
        if pt:
            blocks.append(pt)
        teacher = load(f"teacher_load_d{design}")
        if teacher:
            blocks.append(teacher_table(teacher, label, f"teacher_load_d{design}"))
        verdicts = load(f"verdicts_d{design}")
        if verdicts:
            blocks.append(verdict_table(verdicts, label, f"verdicts_d{design}"))
    robust = robustness_table()
    if robust:
        blocks.append(robust)
    for design, label in DESIGNS.items():
        cost = load(f"speed_cost_d{design}")
        if cost:
            blocks.append(cost_table(cost, label, f"speed_cost_d{design}"))
    body = "\n\n".join("\n".join(b) for b in blocks) if blocks else "Not run yet."
    text = PROOF.read_text()
    head, _, tail = text.partition(HEADING)
    rest = ""
    marker = tail.find("\n## ")
    if marker != -1:
        rest = tail[marker:]
    PROOF.write_text(f"{head}{HEADING}\n\n{body}\n{rest}")
    print(body)


if __name__ == "__main__":
    main()

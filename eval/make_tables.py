import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
RESULTS = ROOT / "eval" / "results"
PROOF = ROOT / "docs" / "proof.md"
HEADING = "## Results (generated by eval/make_tables.py)"
DESIGNS = {"1": "Design 1 (readers judge criteria)", "2": "Design 2 (readers transcribe, code checks the key)"}


def load(name):
    path = RESULTS / f"{name}.json"
    return json.loads(path.read_text()) if path.exists() else None


def cell(stat):
    if stat is None:
        return "not measured"
    if stat.get("spread") is None or len(stat.get("runs") or []) == 1:
        return f"{stat['mean']}%"
    return f"{stat['mean']}% ({stat['min']} to {stat['max']})"


def agreement_table(agreement, published, title="Agreement with the official grade", source="agreement"):
    d = agreement["docket"]
    slice_name = ", ".join(agreement["slice"]) or "unknown"
    scripts = ", ".join(str(n) for n in agreement["scriptsPerRun"])
    models = next(iter(agreement["models"].values())) or {}
    lines = [
        f"### {title} (slice: {slice_name}; scripts per run: {scripts}; runs: {', '.join(agreement['runIds'])})",
        "",
        f"Mean of the runs, min to max in brackets, when more than one run. Source: `eval/results/{source}.json`.",
        "",
        "| Setup | Exact | Within one | Scripts it grades |",
        "|---|---|---|---|",
        f"| Docket, when it signs without a teacher | {cell(d['exactWhenCommitsPct'])} | {cell(d['withinOneWhenCommitsPct'])} | {cell(d['commitsPct'])} of the slice |",
        f"| Docket, teacher-free floor (disputed criteria take the lower reading) | {cell(d['floorExactPct'])} | {cell(d['floorWithinOnePct'])} | all |",
        f"| Reader A alone (`{models.get('a', '?')}`) | {cell(agreement['readerA']['exactPct'])} | {cell(agreement['readerA']['withinOnePct'])} | all |",
        f"| Reader B alone (`{models.get('b', '?')}`) | {cell(agreement['readerB']['exactPct'])} | {cell(agreement['readerB']['withinOnePct'])} | all |",
        f"| Docket with the official grade standing in for the teacher (true by construction on routed scripts) | {cell(d['teacherStandInExactPct'])} | {cell(d['teacherStandInWithinOnePct'])} | all |",
    ]
    modes = agreement.get("mode") or []
    candidates = [r for r in (published or {}).get("rows", []) if not modes or r["mode"] in modes]
    if candidates:
        top = candidates[0]
        lines.append(
            f"| Reference, not run by Docket: best published single model in the CHECK-MAT repo (`{top['model']}`, {top['mode']}, {top['scripts']} scripts) | {top['exactPct']}% | {top['withinOnePct']}% | all |"
        )
    failed = agreement.get("failedCallsRetriedPerRun") or []
    if any(failed):
        parts = []
        for run_id, counts in zip(agreement["runIds"], failed):
            text = ", ".join(f"{m} {n}" for m, n in sorted(counts.items())) or "none"
            parts.append(f"{run_id}: {text}")
        lines += ["", f"Reader calls that failed (wrong tool name, schema break, rate limit) and were retried: {'; '.join(parts)}."]
    dropped = agreement["droppedPerRun"]
    if any(dropped):
        lines += ["", f"Scripts dropped from all setups after reader errors, per run: {', '.join(str(n) for n in dropped)}."]
    return lines


def teacher_table(teacher, label, source):
    rows = [
        ("Criteria routed to the teacher", "criteriaRoutedPct"),
        ("Scripts with at least one routed criterion", "scriptsRoutedPct"),
        ("Routed scripts where the official total differs from reader A", "officialDiffersFromAPct"),
        ("Routed scripts where it differs from reader B", "officialDiffersFromBPct"),
        ("Routed scripts where it differs from at least one reader", "officialDiffersFromAtLeastOnePct"),
        ("Routed scripts where it differs from both readers", "officialDiffersFromBothPct"),
    ]
    lines = [
        f"### {label}: teacher load and what the interrupt catches",
        "",
        f"Source: `eval/results/{source}.json`.",
        "",
        "| Measure | Mean (min to max) |",
        "|---|---|",
    ]
    lines += [f"| {label} | {cell(teacher.get(key))} |" for label, key in rows]
    unread = teacher.get("scriptsUnreadByAReader")
    if unread and unread.get("max"):
        lines.append(f"| Routed scripts where a reader declined or skipped a criterion (count) | {unread['mean']} ({unread['min']} to {unread['max']}) |")
    return lines


def verdict_table(verdicts, label, source):
    rows = [
        ("Exact when it signs vs reader A alone", "exactWhenCommitsVsReaderA"),
        ("Exact when it signs vs reader B alone", "exactWhenCommitsVsReaderB"),
        (f"Teacher-free floor vs the better single reader ({verdicts['bestSingleReader']})", "floorVsBest"),
        ("Signs without a teacher often enough", "commitsShare"),
        ("The interrupt catches real errors", "interruptCatches"),
    ]
    lines = [
        f"### {label}: against the preregistered bar",
        "",
        f"Source: `eval/results/{source}.json`, computed in code from the bar above. Means from {', '.join(verdicts['meansFrom']['runs'])} on {', '.join(verdicts['meansFrom']['slice'])}; spreads from {', '.join(verdicts['spreadsFrom']['runs'])} on {', '.join(verdicts['spreadsFrom']['slice'])}.",
        "",
        "| Claim | Result |",
        "|---|---|",
    ]
    lines += [f"| {label} | {verdicts[key]} |" for label, key in rows]
    return lines


def robustness_table():
    checks = [
        ("Tampered credentials and revocation lists rejected", "tamper"),
        ("Scan-less requests the pipeline refused to grade (blind check, design 2, task-13 scripts of the seeded 61; reader A not run, daily cap; since Amendment 8 code discards every reading made without a student page)", "blind"),
        ("Bad readings blocked before signing (guard), design 1 readings", "guard_d1"),
        ("Bad readings blocked before signing (guard), design 2 readings", "guard_d2"),
    ]
    lines = [
        "### Robustness",
        "",
        "| Check | Result | Source |",
        "|---|---|---|",
    ]
    any_row = False
    for label, name in checks:
        data = load(name)
        if not data:
            continue
        any_row = True
        tag = f" ({data['label']})" if data.get("label") else ""
        lines.append(f"| {label}{tag} | {data['passed']} of {data['total']} | `eval/results/{name}.json` |")
        for part in data.get("parts", []):
            lines.append(f"| &nbsp;&nbsp;{part['label']} | {part['passed']} of {part['total']} | |")
            if "readerDeclined" in part:
                lines.append(f"| &nbsp;&nbsp;{part['label']}: the reader itself declined | {part['readerDeclined']} of {part['total']} | |")
                lines.append(f"| &nbsp;&nbsp;{part['label']}: the reader returned an invented student answer, discarded by code | {part['readerInventedWork']} of {part['total']} | |")
            if "anyCriterionMet" in part:
                lines.append(f"| &nbsp;&nbsp;{part['label']}: gave no point at all (no criterion met, 0 by the scheme) | {part['total'] - part['anyCriterionMet']} of {part['total']} | |")
    for remark_name in ("remark_d1", "remark_d2"):
        remark = load(remark_name)
        if not remark:
            continue
        any_row = True
        lines.append(
            f"| Scheme {remark['from']} to {remark['to']} (design {remark['design']}, {remark['modelCalls']} model calls): re-marked, grade changed, re-issued, revoked | "
            f"{remark['remarked']} re-marked, {remark['reissued']} changed and re-issued, {remark['revoked']} revoked, {remark['unchanged']} unchanged, in {remark['seconds']} s; {remark['checksPassed']} of {remark['checks']} checks pass | `eval/results/{remark_name}.json` |"
        )
    return lines if any_row else []


def cost_table(cost, label, source):
    lines = [
        f"### {label}: seconds and cost per script",
        "",
        f"Source: `eval/results/{source}.json`. Free-tier cost is $0; the estimate is the price sheet's per-token price times the measured tokens.",
        "",
        "| Measure | Value |",
        "|---|---|",
    ]
    s = cost.get("secondsPerScript")
    if s:
        lines.append(f"| Seconds per script, both readers and code (median, mean, max over {s['scriptsTimed']} timed) | {s['median']}, {s['mean']}, {s['max']} |")
    for side, r in cost["readers"].items():
        lines.append(f"| {side} `{r['model']}` mean tokens in / out per script | {r['meanInputTokensPerScript']} / {r['meanOutputTokensPerScript']} |")
        if r.get("priceSheet"):
            lines.append(f"| {side} price-sheet estimate per script ([price page]({r['priceSheet']['url']})) | ${r['priceSheetEstimateUsdPerScript']} |")
    if cost.get("priceSheetEstimateUsdPerScript") is not None:
        lines.append(f"| Both readers, price-sheet estimate per script | ${cost['priceSheetEstimateUsdPerScript']} |")
    if cost.get("bound"):
        lines.append(f"| What bounds the seconds | {cost['bound']} |")
    limits = load("limits")
    for row in (limits or {}).get("rows", []):
        lines.append(f"| Free-tier limit, `{row['provider']}:{row['model']}` (`eval/results/limits.json`) | {row['limit']}: {row['evidence']} |")
    return lines


def ci(agreement, key):
    w = (agreement.get("wilson95") or {}).get(key)
    if not w:
        return "not measured"
    return f"{w['pct']}% ({w['k']}/{w['n']}; 95% CI {w['low']} to {w['high']})"


def paired_table(agreement, label, source):
    pairs = agreement.get("paired")
    if not pairs:
        return []
    names = {
        "floorVsReaderA": ("Docket teacher-free floor", "reader A alone"),
        "floorVsReaderB": ("Docket teacher-free floor", "reader B alone"),
        "readerAVsReaderB": ("reader A alone", "reader B alone"),
        "design2VsDesign1": ("design 2 teacher-free floor", "design 1 teacher-free floor"),
    }
    lines = [
        f"### {label}: paired comparison on the same scripts (exact agreement)",
        "",
        f"Discordant scripts: only the first right, only the second right. Exact two-sided McNemar test. Source: `eval/results/{source}.json`.",
        "",
        "| First | Second | Only first right | Only second right | Both right | Neither | McNemar p |",
        "|---|---|---|---|---|---|---|",
    ]
    for key, p in pairs.items():
        first, second = names.get(key, (key, ""))
        lines.append(f"| {first} | {second} | {p['firstOnlyRight']} | {p['secondOnlyRight']} | {p['bothRight']} | {p['neitherRight']} | {p['mcnemarExactP']} |")
    return lines


